"""What a run sees of the daemon that holds it: the worker's home, config and environment, the hub, the checkouts and
their locks, the tmux and the browsers it shares, and the stop. ``daemon.Daemon`` is one; a run reaches no other part
of it, so the heartbeat, the claims and the cleanup stay the daemon's own (``daemon_*``)."""

from __future__ import annotations

import asyncio
from pathlib import Path
from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    from evo_agents.worker.adapter import Adapter
    from evo_agents.worker.browser.session import BrowserSession
    from evo_agents.worker.home import WorkerConfig, WorkerHome
    from evo_agents.worker.hubapi import HubProblem, WorkerHub
    from evo_agents.worker.interactive import Tmux
    from evo_agents.worker.run import Run
    from evo_agents.worker.spool import SpoolBudget


class RunHost(Protocol):
    """The daemon as its runs use it."""

    @property
    def home(self) -> WorkerHome: ...
    @property
    def config(self) -> WorkerConfig: ...
    @property
    def env(self) -> dict[str, str]: ...
    @property
    def token(self) -> str: ...
    @property
    def hub(self) -> WorkerHub | None: ...
    @property
    def hard_stop(self) -> asyncio.Event: ...
    @property
    def tmux(self) -> Tmux: ...
    @property
    def adapters(self) -> dict[str, type[Adapter]]: ...
    @property
    def runs(self) -> dict[int, Run]: ...
    @property
    def browsers(self) -> dict[int, BrowserSession]: ...
    @property
    def checkouts(self) -> dict[str, dict]: ...
    @property
    def heartbeat_s(self) -> float: ...
    @property
    def budget(self) -> SpoolBudget: ...

    def checkout_for(self, project: str, repo: str) -> Path | None: ...
    def repo_lock(self, checkout: Path) -> asyncio.Lock: ...
    def add_checkout(self, project: str, repo: str, path: Path) -> None: ...
    def fatal(self, problem: HubProblem) -> None: ...
    def saw_agent(self, runtime: str, *, leased: bool, authenticated: bool) -> None: ...
