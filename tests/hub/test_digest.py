def test_the_digest_state_keeps_sessions_per_hub_and_forgets_old_ones(tmp_path):
    state = DigestState(tmp_path, "https://hub.test")
    state.put("old", {"transcript": "/t/old.jsonl", "pending": True}, now=1_000.0)
    state.put("new", {"transcript": "/t/new.jsonl", "pending": True}, now=2_000.0)
    state.put("done", {"transcript": "/t/done.jsonl", "pending": False}, now=3_000.0)
    assert [key for key, _ in state.waiting("new", 3)] == ["old"]
    assert [key for key, _ in state.waiting("someone", 1)] == ["old"]
    assert DigestState(tmp_path, "https://other.test").sessions() == {}
    state.put("later", {"pending": False}, now=1_000.0 + digest.KEEP_SECONDS + 1)
    assert set(state.sessions()) == {"new", "done", "later"}, "a session not pushed for 90 days is forgotten"
    (tmp_path / digest.STATE_FILE).write_text("{broken", encoding="utf-8")
    assert state.sessions() == {}


