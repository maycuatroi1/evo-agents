def at(second: int) -> str:
    return f"2026-10-08T01:00:{second:02d}.000Z"


def said(text: str, second: int, **extra) -> dict:
    return {"type": "user", "message": {"role": "user", "content": text}, "timestamp": at(second), **extra}


def answered(message_id: str, second: int, *content: dict, model: str = MODEL) -> dict:
    message = {"id": message_id, "role": "assistant", "model": model, "content": list(content), "usage": USAGE}
    return {"type": "assistant", "message": message, "timestamp": at(second)}


def tool_use(call_id: str, name: str, **given) -> dict:
    return {"type": "tool_use", "id": call_id, "name": name, "input": given}


def result(call_id: str, second: int, text: str = "ok", error: bool = False) -> dict:
    block = {"type": "tool_result", "tool_use_id": call_id, "content": text, "is_error": error}
    return {"type": "user", "message": {"role": "user", "content": [block]}, "timestamp": at(second)}


def session_lines(turn: str = "Run the tests and fix what fails.", command: str = "python -m pytest -q") -> list[dict]:
    """A session of 13 messages: a test run that fails, a read, an edit, the test run again, a git push that fails."""
    return [
        said("<local-command-caveat>Caveat: the messages below were generated by the user</local-command-caveat>", 0)
        | {"isMeta": True},
        said(turn, 1),
        answered("msg_1", 2, {"type": "text", "text": "Running the tests."}),
        answered("msg_1", 3, tool_use("toolu_1", "Bash", command=f"cd /work/app && {command}")),
        result("toolu_1", 4, FAILED_TEST, error=True),
        answered("msg_2", 5, tool_use("toolu_2", "Read", file_path="/work/app/queue.py")),
        result("toolu_2", 6, "def claim(): ..."),
        answered(
            "msg_3", 7, tool_use("toolu_3", "Edit", file_path="/work/app/queue.py", old_string="a", new_string="b")
        ),
        result("toolu_3", 8),
        answered("msg_4", 9, tool_use("toolu_4", "Bash", command=f"cd /work/app && {command}")),
        result("toolu_4", 10, "12 passed"),
        answered("msg_5", 11, tool_use("toolu_5", "Bash", command="git -C /work/app push")),
        result("toolu_5", 12, "rejected: non-fast-forward", error=True),
        {"type": "system", "subtype": "compact_boundary", "timestamp": at(13)},
        {"type": "file-history-snapshot", "snapshot": {}},
        said("<command-name>/cost</command-name>", 14),
    ]


def write_transcript(path: Path, lines: list[dict]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(line) + "\n" for line in lines) + "not json\n", encoding="utf-8")
    return path


