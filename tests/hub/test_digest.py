"""The digest of a Claude Code session, built on the machine from its transcript (``evo_agents.hub.digest``), and the
Stop hook's side of pushing it (``evo_agents.hub.hooks``) where no hub is needed.

The digest counts messages as the harness-engineering skill's digest does (meta lines and lines of other types left
out, fewer than 6 means no digest), counts calls and failures per tool and per Bash program, keeps what the person wrote
and the text of failed results, cut, counts the tokens of each message of the model once, and names the model most
messages name. The hook sends nothing in a worker run, nothing when not signed in, nothing for a session under 6
messages, and when the hub does not answer it keeps the digest waiting and leaves the hub alone for the cooldown.
``tests.hub.test_session_digests`` pushes digests to a hub on Postgres."""

