def signed_in(home: Path, url: str) -> None:
    directory = home / ".evo" / "hub"
    directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    (directory / "token").write_text("evo_test_token_never_printed\n", encoding="utf-8")
    (directory / "config.json").write_text(json.dumps({"url": url, "login": "alice"}), encoding="utf-8")


def stop(payload: dict, monkeypatch, capsys) -> tuple[int, str, str]:
    monkeypatch.setattr(sys, "stdin", io.StringIO(json.dumps(payload)))
    code = main(["hub", "hook", "stop"])
    out, err = capsys.readouterr()
    return code, out, err


def payload(home: Path, lines: list[dict]) -> dict:
    work = home / "work"
    transcript = write_transcript(home / ".claude" / "projects" / "-work" / f"{SESSION}.jsonl", lines)
    return {"session_id": SESSION, "transcript_path": str(transcript), "cwd": str(work), "hook_event_name": "Stop"}


def test_stop_sends_no_digest_when_not_signed_in_in_a_worker_run_or_under_six_messages(home, monkeypatch, capsys, sent):
    given = payload(home, session_lines())
    assert stop(given, monkeypatch, capsys) == (0, "", "")  # not signed in
    signed_in(home, f"http://127.0.0.1:{pg.free_port()}")
    monkeypatch.setenv(hooks.RUN_VARIABLE, "7")
    assert stop(given, monkeypatch, capsys) == (0, "", "")  # the agent of run #7: its trace is on the hub
    monkeypatch.delenv(hooks.RUN_VARIABLE)
    assert stop(payload(home, session_lines()[:6]), monkeypatch, capsys) == (0, "", "")  # 5 messages
    for broken in ({**given, "session_id": "../etc"}, {**given, "transcript_path": "relative.jsonl"}):
        assert stop(broken, monkeypatch, capsys) == (0, "", "")
    assert sent == [] and not (home / ".evo" / "hub" / digest.STATE_FILE).exists()


def test_a_digest_the_hub_did_not_take_waits_and_the_hub_is_left_alone(home, monkeypatch, capsys, sent):
    url = f"http://127.0.0.1:{pg.free_port()}"
    signed_in(home, url)
    clock = [1_000_000.0]
    monkeypatch.setattr(hooks, "_now", lambda: clock[0])
    given = payload(home, session_lines())
    code, out, err = stop(given, monkeypatch, capsys)
    assert (code, out) == (0, "") and len(sent) == 1  # the projects, to tell the session's: refused
    assert err.startswith("evo-hub: session digest not pushed, the hub did not answer") and err.count("\n") == 1
    assert "evo_test_token" not in err
    waiting = DigestState(home / ".evo" / "hub", url).get(SESSION)
    assert waiting["pending"] is True and waiting["transcript"] == given["transcript_path"]
    assert "sha256" not in waiting and "resolved" not in waiting

    clock[0] += hooks.COOLDOWN - 1
    assert stop(given, monkeypatch, capsys) == (0, "", "") and len(sent) == 1  # not asked again yet
    assert DigestState(home / ".evo" / "hub", url).get(SESSION)["pending"] is True


def test_a_digest_is_marked_waiting_before_its_request_so_a_run_out_of_time_leaves_it(home, monkeypatch, capsys):
    url = f"http://127.0.0.1:{pg.free_port()}"
