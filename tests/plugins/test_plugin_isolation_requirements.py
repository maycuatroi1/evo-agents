"""The requirements file of a backend, which the plugin host reads before pip does (criterion a4 of hub-agent-plugins,
the review's C1 and L1): only ``name==version --hash=sha256:...`` lines pass, so no line can make pip run a build
backend from a directory of the bundle, fetch from an index or a URL, or read another file (``-r /proc/1/environ``),
and a refused line never brings the content of another file into the error an admin reads. The host refuses such a
plugin before pip starts, and pip runs in an empty directory. No pip and no root needed."""

from __future__ import annotations

import asyncio
import json
import os
import stat
from pathlib import Path

import pytest

from evo_agents.plugins import environment
from evo_agents.plugins.environment import PlacementError, build_env, extract, placement, prepare_data
from evo_agents.plugins.host import BackendUnavailable, Host
from evo_agents.plugins.requirements import RequirementsError, normalized, parse_requirements
from tests.plugins.backends import bundle, init, manifest, wheeled_plugin

DIGEST = "a" * 64
OTHER = "B" * 64


def test_plugin_isolation_requirements_accept_hashed_pins_as_pip_compile_writes_them():
    text = (
        "# This file was autogenerated by uv\n"
        f"requests==2.32.3 \\\n    --hash=sha256:{DIGEST} \\\n    --hash=sha256:{OTHER}\n"
        "    # via my-plugin\n"
        f"idna==3.10 --hash=sha256:{DIGEST}  # a comment after a space\n"
        "\n"
    )
    parsed = parse_requirements(text)
    assert [(r.name, r.version) for r in parsed] == [("requests", "2.32.3"), ("idna", "3.10")]
    assert parsed[0].hashes == (DIGEST, OTHER.lower())
    assert normalized(parsed) == (
        f"requests==2.32.3 --hash=sha256:{DIGEST} --hash=sha256:{OTHER.lower()}\nidna==3.10 --hash=sha256:{DIGEST}\n"
    )
    assert parse_requirements("# nothing but comments\n\n") == []


@pytest.mark.parametrize(
    "line",
    [
        "-r /proc/1/environ",
        "--requirement=other.txt",
        "-c constraints.txt",
        "-e ./evil",
        "./evil",
        "evil/",
        "file:///plugins/code/other/1.0.0",
        "https://example.org/evil-1.0.tar.gz",
        "git+https://example.org/evil.git",
        "evil @ file:///tmp/evil",
        f"--index-url https://example.org/simple evil==1.0 --hash=sha256:{DIGEST}",
        f"--find-links /tmp evil==1.0 --hash=sha256:{DIGEST}",
        f"--extra-index-url=https://example.org evil==1.0 --hash=sha256:{DIGEST}",
        "evil>=1.0",
        "evil==1.0",
        f"evil==1.0 --hash=md5:{DIGEST[:32]}",
        f"evil==1.0 --hash=sha256:{DIGEST} --no-binary=:all:",
        f'evil==1.0 ; python_version > "3" --hash=sha256:{DIGEST}',
        f"evil[extra]==1.0 --hash=sha256:{DIGEST}",
        f"evil==1.0 --hash=sha256:{DIGEST}" + " \\\n-r /proc/1/environ",
    ],
)
def test_plugin_isolation_requirements_refuse_every_other_line(line):
    with pytest.raises(RequirementsError, match=r"only lines `name==version --hash=sha256:<64 hex>`"):
        parse_requirements(f"ok==1.0 --hash=sha256:{DIGEST}\n{line}\n")


def test_plugin_hostile_requirements_naming_a_directory_never_reach_pip(plugin_root, tmp_path):
    """The review's C1: a line naming a directory of the bundle made pip run that directory's build backend, even
    with --only-binary and --no-index. The host refuses the file before pip starts, and the backend never runs."""
    directory = wheeled_plugin(tmp_path / "wheeled", requirements="./evil\n")
    evil = directory / "backend" / "evil"
    evil.mkdir()
    (evil / "pyproject.toml").write_text(
        '[build-system]\nrequires = []\nbuild-backend = "backend"\nbackend-path = ["."]\n'
    )
    marker = tmp_path / "build-backend-ran"
    (evil / "backend.py").write_text(f"open({str(marker)!r}, 'w').write('ran')\n")

    async def run():
        host = Host(plugin_root, allow_shared_user=True)
        backend = host.place(manifest("wheeled", directory), bundle("wheeled", directory), init("wheeled", 9))
        with pytest.raises(BackendUnavailable):
            await backend.call("ping", {}, timeout=60)
        await host.stop_all()
        return backend

    backend = asyncio.run(run())
    assert "only lines `name==version" in backend.status.error and "'./evil'" in backend.status.error
    assert not marker.exists() and backend.process is None
    assert not backend.where.env.exists()  # no environment was made from a refused file


def test_plugin_hostile_requirements_reading_another_file_show_nothing_of_it(tmp_path):
    """The review's L1: ``-r /proc/1/environ`` once put the host's environment in the error an admin reads."""
    secret = tmp_path / "secret.txt"
    secret.write_text("EVO_HUB_PLUGIN_HOST_TOKEN=evo-hub-secret-host-token\n")
    directory = wheeled_plugin(tmp_path / "wheeled", requirements=f"-r {secret}\n")
    where = placement(tmp_path / "root", "wheeled", "1.0.0")
    extract(bundle("wheeled", directory), where.code)
    prepare_data(where, None)
    with pytest.raises(PlacementError) as refused:
        build_env(where, "backend/requirements.txt")
    assert "evo-hub-secret" not in str(refused.value)
    assert "not '-r /" in str(refused.value)  # the line itself, cut short, so the author sees what to fix


def test_plugin_isolation_requirements_need_the_wheels_next_to_them(tmp_path):
    directory = wheeled_plugin(tmp_path / "wheeled")
    for wheel in (directory / "backend" / "wheels").iterdir():
        wheel.unlink()
    (directory / "backend" / "wheels").rmdir()
    data = json.loads((directory / "evo-plugin.json").read_text())
    where = placement(tmp_path / "root", data["id"], data["version"])
    extract(bundle("wheeled", directory), where.code)
    prepare_data(where, None)
    with pytest.raises(PlacementError, match="no wheels/ next to it"):
        build_env(where, "backend/requirements.txt")


@pytest.mark.parametrize(
    "version",
    ["1.tar.gz", "1+x.tar.gz", "1+x.zip", "1+x.whl", "1+x.tgz", "1+x.tar", "1.0-beta", "1.0.0.", "v1.0", "1.0+X"],
)
def test_plugin_hostile_requirements_naming_an_archive_never_reach_pip(version):
    """The review's second L1: pip reads ``foo==1.tar.gz`` as a file of its current directory and builds it, even with
    --only-binary and --no-index. Only a normalized PEP 440 version passes, and never one that ends like an archive."""
    with pytest.raises(RequirementsError, match=r"only lines `name==version --hash=sha256:<64 hex>`"):
        parse_requirements(f"evil=={version} --hash=sha256:{DIGEST}\n")


@pytest.mark.parametrize("version", ["1.0", "2!1.0", "1.0a1", "1.0rc2", "1.0.post1", "1.0.dev3", "2.1.0+cpu.1"])
def test_plugin_isolation_requirements_accept_every_normalized_version(version):
    assert parse_requirements(f"ok=={version} --hash=sha256:{DIGEST}\n")[0].version == version


def test_plugin_isolation_requirements_pip_runs_in_an_empty_directory_no_one_writes(tmp_path, monkeypatch):
    """venv and pip run in a directory of their own that holds nothing and that only root may write, removed after,
    so no file there can stand for a requirement."""
    directory = wheeled_plugin(tmp_path / "wheeled")
    where = placement(tmp_path / "root", "wheeled", "1.0.0")
    extract(bundle("wheeled", directory), where.code)
    prepare_data(where, None)
    seen: list[tuple[str, Path, list[str], int]] = []

    def recording(command, doing, where_, cwd, owner=None):
        seen.append((doing, Path(cwd), os.listdir(cwd), stat.S_IMODE(os.stat(cwd).st_mode)))

    monkeypatch.setattr(environment, "_run", recording)
    build_env(where, "backend/requirements.txt")
    assert [doing.split()[0] for doing, *_ in seen] == ["make", "install"]
    for _, cwd, listed, mode in seen:
        assert listed == [] and mode == 0o555
        assert cwd.parent == where.env.parent and cwd not in (where.env, where.code, where.data)
        assert not cwd.exists()
