/** The logo of a provider at 20 px; decorative, as the provider's name is text beside it. */
export function ProviderLogo({ provider, className }: { provider: Provider; className?: string }) {
  const mark = MARKS[provider];
  const box = cn("inline-flex size-5 shrink-0 items-center justify-center", className);
  if (mark.kind === "tile") {
    return (
      <span aria-hidden="true" data-provider={provider} className={cn(box, "rounded-[5px] text-[11px] font-semibold leading-none", mark.className)}>
        {mark.letter}
      </span>
    );
  }
  return (
    <span aria-hidden="true" data-provider={provider} className={cn(box, "text-foreground")}>
      {mark.kind === "path" ? (
        <svg viewBox="0 0 24 24" focusable="false" className="size-5" style={mark.color ? { color: mark.color } : undefined}>
          <path fill="currentColor" d={mark.path} />
        </svg>
      ) : mark.kind === "github" ? (
        <GitHubMark className="size-5" />
      ) : (
        <KeyRound className="size-4 text-fg-subtle" />
      )}
    </span>
  );
}
